export class LyricsEngine {
  constructor() {
    this.currentLyrics = null;
    this.activeLineIdx = -1;
  }

  getLyricsForTrack(title) {
    if (!title) return null;
    // Direct match
    if (TRACK_LYRICS_DB[title]) return TRACK_LYRICS_DB[title];

    // Substring match
    const cleanTitle = title.toLowerCase();
    for (const [key, data] of Object.entries(TRACK_LYRICS_DB)) {
      if (cleanTitle.includes(key.toLowerCase()) || key.toLowerCase().includes(cleanTitle)) {
        return data;
      }
    }

    // Default acoustic lore generator
    return {
      hasSynced: false,
      language: 'Hi-Res Lossless Master',
      lore: `Acoustic analysis for "${title}". Rendered with 64-band real-time FFT spectrum processing, 24-bit/96kHz harmonic reconstruction, and bit-perfect hardware passthrough.`,
      lines: [
        { time: 0, text: `♪ Listening to "${title}" ♪`, translation: "Audiophile Bit-Perfect Playback" },
        { time: 30, text: "High-resolution stereo stage with dynamic harmonic overtones.", translation: "Acoustic Stage Active" },
        { time: 90, text: "Enjoying studio quality sound in Resonix Studio.", translation: "Lossless Audio Experience" }
      ]
    };
  }

  getActiveLineIndex(lyrics, currentTime) {
    if (!lyrics || !lyrics.lines || lyrics.lines.length === 0) return -1;
    let active = 0;
    for (let i = 0; i < lyrics.lines.length; i++) {
      if (currentTime >= lyrics.lines[i].time) {
        active = i;
      } else {
        break;
      }
    }
    return active;
  }
}

export const lyricsEngine = new LyricsEngine();
